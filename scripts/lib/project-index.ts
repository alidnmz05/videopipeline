import fs from 'node:fs';
import path from 'node:path';
import {PROJECTS_DIR, assertSlug} from './project';

const OUT = 'src/projects.generated.ts';

// Remotion bundles with webpack and cannot list files at runtime, so every project
// that has a story.json gets a static import in a generated module, one composition each.
export const writeProjectIndex = () => {
  const slugs = fs.existsSync(PROJECTS_DIR)
    ? fs.readdirSync(PROJECTS_DIR).filter((s) => fs.existsSync(path.join(PROJECTS_DIR, s, 'story.json'))).sort()
    : [];
  slugs.forEach(assertSlug);

  const lines = [
    '// Generated by scripts/lib/project-index.ts. Do not edit; rerun `npm run index`.',
    "import type {Story} from './types';",
    ...slugs.map((s, i) => `import p${i} from '../${PROJECTS_DIR}/${s}/story.json';`),
    '',
    'export const projects: {id: string; story: Story}[] = [',
    ...slugs.map((s, i) => `  {id: '${s}', story: p${i} as Story},`),
    '];',
    '',
  ];
  const content = lines.join('\n');
  if (!fs.existsSync(OUT) || fs.readFileSync(OUT, 'utf8') !== content) fs.writeFileSync(OUT, content);
  return slugs;
};
